from enum import Enum

from pydantic import BaseModel, Field


class AlternativeStatus(str, Enum):
    GENERATED = "GENERATED"
    VALIDATED = "VALIDATED"
    REJECTED  = "REJECTED"


class AlternativeResult(BaseModel):
    """
    Candidate safer command generated by the reasoning engine.

    The candidate must be validated by the rule engine before
    being presented as a trusted safer alternative.
    """

    original_command: str = Field(min_length=1)

    candidate_command: str = Field(min_length=1)

    intent: str = Field(min_length=1)

    strategy: str = Field(min_length=1)

    explanation: str = Field(min_length=1)

    status: AlternativeStatus = AlternativeStatus.GENERATED
